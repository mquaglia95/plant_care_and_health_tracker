/**
 * Generate the species catalog migration from species_seed.json.
 *
 * species_seed.json is the source of truth; the migration is derived. Edit the
 * JSON, re-run this, and commit both.
 *
 *   node scripts/gen_species_migration.js
 *
 * Replaces import_species.js (the Perenual pull), which bucketed watering into
 * four values, stored light as a joined string, and set is_toxic_to_cats=true
 * on every row regardless of the plant.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SEED = path.join(ROOT, 'species_seed.json');
const OUT = path.join(ROOT, 'supabase/migrations/20261008120200_load_species_catalog.sql');

const LIGHT = new Set(['low','low_medium','medium','medium_bright','bright_indirect','direct_sun']);
const DIFF = new Set(['easy','moderate','hard']);
const HABIT = new Set(['upright','trailing','vining','climbing','creeping',
                       'clumping','rosette','tree','shrub','epiphyte','globular']);

const COLS = ['slug','common_name','scientific_name','family','difficulty','light',
  'water_days_baseline','water_days_min','water_days_max','water_notes',
  'humidity_min_pct','temp_min_f','temp_max_f','fertilizer','soil',
  'is_toxic_to_cats','is_toxic_to_dogs','growth_habit','mature_size',
  'common_problems','propagation','winter_adjustment'];

const FROM = { is_toxic_to_cats: 'toxic_cats', is_toxic_to_dogs: 'toxic_dogs' };

const esc = (s) => String(s).replace(/'/g, "''");

function lit(v) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) {
    if (!v.length) return "'{}'";
    const inner = v.map((x) => '"' + x.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"').join(',');
    return "'{" + esc(inner) + "}'";
  }
  return "'" + esc(v) + "'";
}

/**
 * Validate before generating. The watering band in particular is a guardrail
 * the agent relies on -- a row where baseline sits outside [min, max] would
 * let it adjust past the bound without triggering a confirmation.
 */
function validate(rows) {
  const errors = [];
  const slugs = new Set();
  rows.forEach((p, i) => {
    const at = `[${i}] ${p.slug || p.scientific_name || '?'}`;
    if (!p.slug) errors.push(`${at}: missing slug`);
    else if (slugs.has(p.slug)) errors.push(`${at}: duplicate slug`);
    else slugs.add(p.slug);
    if (!p.scientific_name) errors.push(`${at}: missing scientific_name`);
    if (!LIGHT.has(p.light)) errors.push(`${at}: bad light "${p.light}"`);
    if (!DIFF.has(p.difficulty)) errors.push(`${at}: bad difficulty "${p.difficulty}"`);
    if (!HABIT.has(p.growth_habit)) errors.push(`${at}: bad growth_habit "${p.growth_habit}"`);
    const lo = p.water_days_min, b = p.water_days_baseline, hi = p.water_days_max;
    if (!(lo > 0)) errors.push(`${at}: water_days_min must be > 0`);
    if (!(lo <= b && b <= hi)) errors.push(`${at}: water band out of order (${lo} <= ${b} <= ${hi})`);
    if (!(p.humidity_min_pct >= 0 && p.humidity_min_pct <= 100)) errors.push(`${at}: humidity out of range`);
    if (!(p.temp_min_f < p.temp_max_f)) errors.push(`${at}: temp range out of order`);
    if (typeof p.toxic_cats !== 'boolean') errors.push(`${at}: toxic_cats must be boolean`);
    if (typeof p.toxic_dogs !== 'boolean') errors.push(`${at}: toxic_dogs must be boolean`);
    if (!Array.isArray(p.common_problems)) errors.push(`${at}: common_problems must be an array`);
  });
  return errors;
}

const CASTS = {
  difficulty: '::public.care_difficulty',
  light: '::public.light_level',
  growth_habit: '::public.growth_habit',
  common_problems: '::text[]',
};

const rows = JSON.parse(fs.readFileSync(SEED, 'utf8'));
const errors = validate(rows);
if (errors.length) {
  console.error(`${errors.length} validation error(s):`);
  errors.forEach((e) => console.error(`  ${e}`));
  process.exit(1);
}

const values = rows.map((p) =>
  '  (' + COLS.map((c) => lit(p[FROM[c] || c]) + (CASTS[c] || '')).join(', ') + ')'
).join(',\n');

const updates = COLS.filter((c) => c !== 'slug')
  .map((c) => `  ${c} = excluded.${c}`).join(',\n') + ',\n  updated_at = now()';

const sql = `-- Load the curated species catalog and retire the Perenual rows.
--
-- GENERATED by scripts/gen_species_migration.js from species_seed.json.
-- Edit the JSON and regenerate; do not hand-edit this file.
--
-- Shipped as a migration rather than a one-off script so \`supabase db reset\`
-- reproduces the full catalog.

insert into public.species_dim (
  ${COLS.join(',\n  ')}
) values
${values}
on conflict (slug) do update set
${updates};

-- ---------------------------------------------------------------------------
-- Retire the Perenual rows.
--
-- They are identifiable by slug is null. The sample plants from
-- 20260201182810_sample_data.sql reference them, so repoint those first or the
-- delete fails on my_plants_dim_species_id_fkey.
-- ---------------------------------------------------------------------------

update public.my_plants_dim m
set species_id = (
  select s.species_id
  from public.species_dim s
  where s.slug is not null
  order by random()
  limit 1
)
where m.species_id in (
  select species_id from public.species_dim where slug is null
);

delete from public.species_dim where slug is null;

-- ---------------------------------------------------------------------------
-- Tighten now that every row is curated.
-- ---------------------------------------------------------------------------

alter table public.species_dim alter column slug       set not null;
alter table public.species_dim alter column light      set not null;
alter table public.species_dim alter column difficulty set not null;

alter table public.species_dim validate constraint species_water_band_ordered;
alter table public.species_dim validate constraint species_water_band_positive;
alter table public.species_dim validate constraint species_humidity_pct_range;
alter table public.species_dim validate constraint species_temp_range_ordered;
`;

fs.writeFileSync(OUT, sql);
console.log(`Validated ${rows.length} species.`);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${sql.length} bytes).`);
